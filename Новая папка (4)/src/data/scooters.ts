export interface ScooterSpec {
  id: ScooterId;
  name: string;
  subtitle: string;
  price: number;
  caseOnly?: boolean; // Выпадает только из кейса
  power: number;      // pw — мощность газа
  multiplier: number; // m — множитель монет
  maxKmh: number;     // реальная максимальная скорость (км/ч)
  accent: string;
  underglow?: string;
  seated?: boolean;   // Сидячая посадка (M2, Wish 01)
  seatX?: number;
  seatY?: number;
  /** Координаты кончика бугеля (0..1) для реального чирка об асфальт */
  bugelX?: number;
  bugelY?: number;
  spriteSrc: string;      // Вырезанный прозрачный PNG (развёрнут направо)
  originalSrc: string;    // Исходное фото пользователя (fallback)
  // Калибровка спрайта в нормализованных координатах (0..1)
  spriteH: number;
  aspect: number;
  rearX: number;
  rearY: number;
  frontX: number;
  frontY: number;
  bottomY: number;
  deckY: number;
  backFootX: number;
  frontFootX: number;
  gripX: number;
  gripY: number;
  baseTiltDeg: number;
}

